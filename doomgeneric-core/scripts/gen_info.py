#!/usr/bin/env python3
"""Generate `src/info.rs` and `src/sounds.rs` from the C data LUTs.

Converts the pure-data tables in doomgeneric/{info.h,info.c,d_items.c,
sounds.h,sounds.c,p_mobj.h} into Rust static arrays. The output is
checked in; this script is a dev tool for regeneration.

Usage:  python3 scripts/gen_info.py    (from rust/doomgeneric-core)
"""

import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
C = ROOT / "doomgeneric"
OUT = ROOT / "rust" / "doomgeneric-core" / "src"

HEADER = "// Generated by scripts/gen_info.py from the C LUTs - DO NOT EDIT BY HAND.\n"


def cenum(path: Path, name: str, skip: set[str]) -> list[str]:
    text = path.read_text()
    found = None
    for m in re.finditer(r"typedef\s+enum\s*\{(.*?)\}\s*(\w+_t)\s*;", text, re.S):
        if m.group(2) == name:
            found = m.group(1)
            break
    assert found is not None, f"enum {name} not found in {path}"
    out: list[str] = []
    for line in found.splitlines():
        line = line.split("//")[0]
        for tok in line.split(","):
            tok = tok.strip()
            if tok and tok not in skip:
                out.append(tok)
    return out


def region(text: str, start_pat: re.Pattern) -> list[str]:
    m = start_pat.search(text)
    assert m, f"region start {start_pat.pattern} not found"
    tail = text[m.end():].splitlines(keepends=True)
    out = []
    for line in tail:
        if re.match(r"^\};?\s*$", line):
            break
        out.append(line)
    return out


def wrap(items: list[str], per: int = 4, indent: str = "    ") -> str:
    lines = []
    for i in range(0, len(items), per):
        lines.append(indent + ", ".join(items[i:i + per]) + ",")
    return "\n".join(lines)


def enum_decl(name: str, tokens: list[str], repr_: str) -> str:
    body = wrap(tokens, per=1)
    return f"#[repr({repr_})]\n#[derive(Clone, Copy, Debug, Eq, PartialEq)]\npub enum {name} {{\n{body}\n}}\n"


# ---------------------------------------------------------------------------
# sounds.rs
# ---------------------------------------------------------------------------

sfx_tokens = cenum(C / "sounds.h", "sfxenum_t", {"NUMSFX"})
music_tokens = cenum(C / "sounds.h", "musicenum_t", {"NUMMUSIC"})

sounds = open(C / "sounds.c").read()
sfx_names = re.findall(r'SOUND(?:_LINK)?\("(\w+)"', sounds)
music_names = ["None"] + re.findall(r'MUSIC\("(\w+)"\)', sounds)

assert len(sfx_tokens) == 109, len(sfx_tokens)
assert len(sfx_names) == 109, len(sfx_names)
assert len(music_tokens) == 68, len(music_tokens)
assert len(music_names) == 68, len(music_names)

out_sounds = []
out_sounds.append(HEADER)
out_sounds.append("#![allow(non_camel_case_types, clippy::all)]\n")
out_sounds.append(enum_decl("Sfx", sfx_tokens, "u8"))
out_sounds.append(f"pub const NUMSFX: usize = {len(sfx_tokens)};\n")
out_sounds.append(enum_decl("Music", music_tokens, "u16"))
out_sounds.append(f"pub const NUMMUSIC: usize = {len(music_tokens)};\n")
out_sounds.append(
    "/// Identity table `index -> Music` (level-music arithmetic).\n"
    f"pub static MUSIC_BY_INDEX: [Music; {len(music_tokens)}] = [\n"
    + "".join(f"    Music::{t},\n" for t in music_tokens)
    + "];\n"
)
out_sounds.append("""
impl Music {
    /// Table index -> enum (see `MUSIC_BY_INDEX`).
    pub fn from_index(i: i32) -> Music {
        MUSIC_BY_INDEX[i as usize]
    }
}
""")
out_sounds.append(
    "// Lump names (from S_sfx[] in sounds.c); the DS prefix is applied by the host.\n"
)
out_sounds.append(f"pub static SFX_NAMES: [&str; {len(sfx_names)}] = [\n")
out_sounds.append(wrap([f'"{n}"' for n in sfx_names], per=4))
out_sounds.append("];\n")
out_sounds.append(f"pub static MUSIC_NAMES: [&str; {len(music_names)}] = [\n")
out_sounds.append(wrap([f'"{"" if n == "None" else n}"' for n in music_names], per=4))
out_sounds.append("];\n")

(OUT / "sounds.rs").write_text("\n".join(out_sounds))
print("wrote", OUT / "sounds.rs")

# ---------------------------------------------------------------------------
# info.rs
# ---------------------------------------------------------------------------

sprite_tokens = cenum(C / "info.h", "spritenum_t", {"NUMSPRITES"})
state_tokens = cenum(C / "info.h", "statenum_t", {"NUMSTATES"})
mobj_tokens = cenum(C / "info.h", "mobjtype_t", {"NUMMOBJTYPES"})
assert len(sprite_tokens) == 138, len(sprite_tokens)
assert len(state_tokens) == 967, len(state_tokens)
assert len(mobj_tokens) == 137, len(mobj_tokens)

# mobj flags (p_mobj.h mobjflag_t)
mf_flag = {}
for line in (C / "p_mobj.h").read_text().splitlines():
    m = re.match(r"\s*(\w+)\s*=\s*(0x[0-9a-fA-F]+|\d+)\s*,?", line)
    if m and m.group(1).startswith("MF_"):
        mf_flag[m.group(1)] = int(m.group(2), 0)
assert "MF_SOLID" in mf_flag and "MF_SPECIAL" in mf_flag


def eval_expr(v: str, kind: str) -> str:
    """Return a Rust expression for a mobjinfo field value.

    kind is one of "state", "sound", "flags", "int". Integer 0 is the C
    shorthand for statenum S_NULL / sfxenum sfx_None.
    """
    v = v.strip()
    if m := re.fullmatch(r"(-?\d+)\s*\*\s*FRACUNIT", v):
        return str(int(m.group(1)) << 16)
    if m := re.fullmatch(r"FRACUNIT\s*\*\s*(\d+)", v):
        return str((1 << 16) * int(m.group(1)))
    if v == "FRACUNIT":
        return str(1 << 16)
    if re.fullmatch(r"sfx_\w+", v):
        return f"Sfx::{v}"
    if re.fullmatch(r"S_\w+", v):
        return f"StateId::{v}"
    if re.fullmatch(r"-?\d+", v):
        n = int(v)
        if n == 0:
            if kind == "state":
                return "StateId::S_NULL"
            if kind == "sound":
                return "Sfx::sfx_None"
        return v
    # bitmap flags
    parts = v.split("|")
    if parts and all(p.strip() in mf_flag for p in parts):
        return str(sum(mf_flag[p.strip()] for p in parts))
    raise SystemExit(f"cannot evaluate mobjinfo expression: {v!r}")


STATE_FIELDS = {"spawnstate", "seestate", "painstate", "meleestate", "missilestate",
                "deathstate", "xdeathstate", "raisestate"}
SOUND_FIELDS = {"seesound", "attacksound", "painsound", "deathsound", "activesound"}


def field_kind(f: str) -> str:
    if f in STATE_FIELDS:
        return "state"
    if f in SOUND_FIELDS:
        return "sound"
    if f == "flags":
        return "flags"
    return "int"


info_c = open(C / "info.c").read()

# sprnames
spr_region = region(info_c, re.compile(r"char\s*\*\s*sprnames\[\]\s*=\s*\{"))
spr_names = re.findall(r'"(\w+)"', "".join(spr_region))
assert len(spr_names) == 138, len(spr_names)
for i, n in enumerate(spr_names):
    assert n == sprite_tokens[i].removeprefix("SPR_"), (i, n, sprite_tokens[i])

# states
st_region = region(info_c, re.compile(r"state_t\s+states\[NUMSTATES\]\s*=\s*\{"))
states = []
action_tokens = []
row_re = re.compile(
    r'^\s*\{(\w+),(-?\d+),(-?\d+),\{(\w+)\},(\w+),(-?\d+),(-?\d+)\},?\s*(//.*)?$'
)
for line in st_region:
    if not line.strip():
        continue
    m = row_re.match(line)
    assert m, f"bad states row: {line!r}"
    g = m.groups()
    sprite, frame, tics, action, nxt = g[0], g[1], g[2], g[3], g[4]
    misc1, misc2 = int(g[5]), int(g[6])
    assert sprite in sprite_tokens, sprite
    assert nxt in state_tokens, nxt
    # C writes {NULL}; map that to the Action::Null variant.
    rust_action = "Null" if action == "NULL" else action
    if rust_action not in action_tokens:
        action_tokens.append(rust_action)
    states.append((sprite, int(frame), int(tics), rust_action, nxt, misc1, misc2))
assert len(states) == 967, len(states)
action_tokens = [t for t in action_tokens if t != "Null"]

# mobjinfo
mi_region = region(info_c, re.compile(r"mobjinfo_t\s+mobjinfo\[NUMMOBJTYPES\]\s*=\s*\{"))
FIELD_NAMES = [
    "doomednum", "spawnstate", "spawnhealth", "seestate", "seesound",
    "reactiontime", "attacksound", "painstate", "painchance", "painsound",
    "meleestate", "missilestate", "deathstate", "xdeathstate", "deathsound",
    "speed", "radius", "height", "mass", "damage", "activesound", "flags",
    "raisestate",
]
mobjs = []
field_re = re.compile(r"^\s*(.+?)\s*,?\s*//\s*(\w+)\s*$")
entries = [[]]
for line in mi_region:
    if not line.strip():
        continue
    if re.match(r"^\s*\{\s*//\s*MT_", line):
        continue
    if re.match(r"^\s*\{\s*$", line):
        continue
    if re.match(r"^\s*\},?\s*$", line):
        entries.append([])
        continue
    m = field_re.match(line)
    assert m, f"bad mobjinfo line: {line!r}"
    if m.group(2) in FIELD_NAMES:
        entries[-1].append(m)
entries = [e for e in entries if e]
assert len(entries) == 137, len(entries)
for e in entries:
    got = [x.group(2) for x in e]
    assert got == FIELD_NAMES, got

mobjs = []
for e in entries:
    vals = [eval_expr(x.group(1), field_kind(x.group(2))) for x in e]
    mobjs.append(vals)

# weaponinfo (d_items.c)
di = open(C / "d_items.c").read()
wi_region = region(di, re.compile(r"weaponinfo_t\s+weaponinfo\[NUMWEAPONS\]\s*=\s*\{"))
AMMO = {"am_clip": "Clip", "am_shell": "Shell", "am_cell": "Cell", "am_misl": "Missile"}
weapons = []
cur = None
for line in wi_region:
    if not line.strip():
        continue
    if re.match(r"^\s*\{\s*$", line):
        cur = []
    elif re.match(r"^\s*\},\s*$", line) or re.match(r"^\s*\}$", line):
        assert cur is not None and len(cur) == 6, cur
        weapons.append(cur)
        cur = None
    else:
        toks = re.findall(r"\b(?:am_\w+|S_\w+)\b", line)
        cur.extend(toks)
assert len(weapons) == 9, len(weapons)

